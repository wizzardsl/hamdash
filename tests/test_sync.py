"""Logbook sync: LoTW and the QRZ logbook.

Nothing here touches the real services. What is worth guarding is the parts
that would be wrong in a way you only find out about later: a pull that
duplicates the log, a failure reported as a success, and the claim that a LoTW
upload can be done with a password.

Run with:  python -m unittest discover -s tests
"""
import tempfile
import time
import unittest
from pathlib import Path
from unittest import mock

import requests

from hamdash.services.logbook import Logbook
from hamdash.services.qsl import Lotw, QrzLogbook, Runner, SyncError

ADIF = """Generated by LoTW
<PROGRAMID:4>LoTW <EOH>
<CALL:5>W1AW <QSO_DATE:8>20260101 <TIME_ON:4>1200 <BAND:3>20m <MODE:3>SSB \
<QSL_RCVD:1>Y <GRIDSQUARE:6>FN31PR <EOR>
<CALL:5>K1JT <QSO_DATE:8>20260102 <TIME_ON:4>1300 <BAND:3>40m <MODE:2>CW <EOR>
"""


def fake_response(text, status=200):
    r = mock.Mock()
    r.status_code = status
    r.text = text
    return r


def a_log() -> Logbook:
    return Logbook(Path(tempfile.mkdtemp(prefix="hamdash-sync-")) / "l.sqlite3")


class TestLotwPull(unittest.TestCase):
    def test_returns_adif(self):
        lotw = Lotw("me", "pw")
        with mock.patch("hamdash.services.qsl.requests.get",
                        return_value=fake_response(ADIF)) as get:
            self.assertIn("<CALL:5>W1AW", lotw.pull())
        self.assertNotIn("qso_startdate", get.call_args.kwargs["params"])

    def test_since_is_sent_as_a_dashed_date(self):
        """ADIF dates are yyyymmdd; this endpoint wants yyyy-mm-dd."""
        with mock.patch("hamdash.services.qsl.requests.get",
                        return_value=fake_response(ADIF)) as get:
            Lotw("me", "pw").pull(since="20260101")
        self.assertEqual(get.call_args.kwargs["params"]["qso_startdate"],
                         "2026-01-01")

    def test_no_credentials_says_where_to_put_them(self):
        with self.assertRaises(SyncError) as cm:
            Lotw().pull()
        self.assertIn("Settings", str(cm.exception))

    def test_a_login_page_is_not_a_log(self):
        """LoTW answers a bad password with HTML and a 200, so status codes
        cannot be trusted here."""
        with mock.patch("hamdash.services.qsl.requests.get",
                        return_value=fake_response("<html>Login required</html>")):
            with self.assertRaises(SyncError) as cm:
                Lotw("me", "wrong").pull()
        self.assertIn("username or password", str(cm.exception))

    def test_network_failure_is_reported_not_raised_raw(self):
        with mock.patch("hamdash.services.qsl.requests.get",
                        side_effect=requests.ConnectionError("no route")):
            with self.assertRaises(SyncError):
                Lotw("me", "pw").pull()


class TestLotwPush(unittest.TestCase):
    def test_without_tqsl_it_refuses_and_explains(self):
        """The important one. A LoTW upload is signed by a certificate that
        lives inside TQSL, so no username and password can stand in for it."""
        lotw = Lotw("me", "pw")
        with mock.patch.object(lotw, "tqsl", return_value=None):
            with self.assertRaises(SyncError) as cm:
                lotw.push("<EOH>")
        msg = str(cm.exception)
        self.assertIn("TQSL", msg)
        self.assertIn("Export ADIF", msg)

    def test_a_nonzero_exit_is_a_failure_with_tqsl_own_words(self):
        lotw = Lotw("me", "pw")
        done = mock.Mock(returncode=1, stdout="", stderr="no station location")
        with mock.patch.object(lotw, "tqsl", return_value="/usr/bin/tqsl"), \
             mock.patch("hamdash.services.qsl.subprocess.run", return_value=done):
            with self.assertRaises(SyncError) as cm:
                lotw.push("<EOH>")
        self.assertIn("no station location", str(cm.exception))

    def test_success(self):
        lotw = Lotw("me", "pw")
        done = mock.Mock(returncode=0, stdout="Uploaded 3 QSOs", stderr="")
        with mock.patch.object(lotw, "tqsl", return_value="/usr/bin/tqsl"), \
             mock.patch("hamdash.services.qsl.subprocess.run", return_value=done):
            self.assertTrue(lotw.push("<EOH>")["ok"])


class TestQrz(unittest.TestCase):
    def test_key_required(self):
        with self.assertRaises(SyncError) as cm:
            QrzLogbook().status()
        self.assertIn("API key", str(cm.exception))

    def test_status(self):
        body = "RESULT=OK&COUNT=1234&BOOKNAME=My+Log&OWNER=VE7ABC"
        with mock.patch("hamdash.services.qsl.requests.post",
                        return_value=fake_response(body)):
            s = QrzLogbook("k").status()
        self.assertEqual(s["count"], "1234")
        self.assertEqual(s["book_name"], "My Log")     # + decoded, not left in

    def test_a_bad_key_is_named_as_such(self):
        with mock.patch("hamdash.services.qsl.requests.post",
                        return_value=fake_response("RESULT=AUTH&REASON=bad+key")):
            with self.assertRaises(SyncError) as cm:
                QrzLogbook("k").status()
        self.assertIn("subscription", str(cm.exception))

    def test_a_refusal_carries_qrz_reason(self):
        with mock.patch("hamdash.services.qsl.requests.post",
                        return_value=fake_response("RESULT=FAIL&REASON=duplicate")):
            with self.assertRaises(SyncError) as cm:
                QrzLogbook("k").push_record("<EOR>")
        self.assertIn("duplicate", str(cm.exception))

    def test_insert_sends_the_record(self):
        with mock.patch("hamdash.services.qsl.requests.post",
                        return_value=fake_response("RESULT=OK&LOGID=99")) as post:
            out = QrzLogbook("k").push_record("<CALL:5>W1AW <EOR>")
        self.assertEqual(out["logid"], "99")
        sent = post.call_args.kwargs["data"]
        self.assertEqual(sent["ACTION"], "INSERT")
        self.assertIn("W1AW", sent["ADIF"])


class TestPullIntoTheLog(unittest.TestCase):
    """A pull that duplicates the log is worse than one that fails."""

    def test_pulling_twice_adds_nothing_the_second_time(self):
        log = a_log()
        first = log.import_adif(ADIF)
        second = log.import_adif(ADIF)
        self.assertEqual(first["added"], 2)
        self.assertEqual(second["added"], 0)
        self.assertEqual(log.stats()["total"], 2)

    def test_a_confirmation_lands_on_the_existing_qso(self):
        log = a_log()
        log.add({"call": "W1AW", "qso_date": "20260101", "time_on": "1158",
                 "band": "20m", "mode": "SSB"})
        res = log.import_adif(ADIF)
        self.assertEqual(res["updated"], 1)        # W1AW merged, 2 min apart
        self.assertEqual(res["added"], 1)          # K1JT is new
        w = [q for q in log.recent() if q["call"] == "W1AW"][0]
        self.assertEqual(w["qsl_rcvd"], "Y")
        self.assertEqual(w["gridsquare"], "FN31PR")

    def test_a_different_band_is_a_different_qso(self):
        log = a_log()
        log.add({"call": "W1AW", "qso_date": "20260101", "time_on": "1200",
                 "band": "40m", "mode": "SSB"})
        self.assertEqual(log.import_adif(ADIF)["added"], 2)

    def test_hours_apart_is_a_different_qso(self):
        log = a_log()
        log.add({"call": "W1AW", "qso_date": "20260101", "time_on": "2300",
                 "band": "20m", "mode": "SSB"})
        self.assertEqual(log.import_adif(ADIF)["added"], 2)


class TestRunner(unittest.TestCase):
    def wait(self, runner, limit=3.0):
        end = time.time() + limit
        while runner.busy() and time.time() < end:
            time.sleep(0.01)

    def test_result_and_start_are_both_announced(self):
        seen = []
        r = Runner(lambda topic, p: seen.append(p["message"]))
        r.start("job", lambda: {"message": "done"})
        self.wait(r)
        self.assertEqual(seen[0], "working…")
        self.assertEqual(seen[-1], "done")
        self.assertTrue(r.state["ok"])

    def test_a_sync_error_is_the_message_not_a_crash(self):
        r = Runner(lambda *a: None)
        r.start("job", lambda: (_ for _ in ()).throw(SyncError("bad password")))
        self.wait(r)
        self.assertFalse(r.state["ok"])
        self.assertEqual(r.state["message"], "bad password")

    def test_an_unexpected_error_does_not_escape(self):
        """A sync parses someone else's output; a surprise there must not take
        the host with it."""
        r = Runner(lambda *a: None)
        r.start("job", lambda: (_ for _ in ()).throw(KeyError("ADIF")))
        self.wait(r)
        self.assertFalse(r.state["ok"])
        self.assertIn("unexpectedly", r.state["message"])

    def test_one_at_a_time(self):
        r = Runner(lambda *a: None)
        r.start("slow", lambda: time.sleep(0.5))
        with self.assertRaises(SyncError) as cm:
            r.start("other", lambda: None)
        self.assertIn("still running", str(cm.exception))
        self.wait(r)


